/** RFQ document per invited vendor (PRD 7.2 outputs: "RFQ PDF per vendor"). */
import PDFDocument from 'pdfkit';
import { get } from '../../core/db.ts';
import { linesOf, fmtIST, type Rfq } from './service.ts';

const NAVY = '#082D53';
const AMBER = '#F4B719';
const GREY = '#5b6b7f';

export function rfqPdf(r: Rfq, vendorId: number | null): Promise<Buffer> {
  const vendor = vendorId ? get<{ name: string; sap_code: string | null; address: string | null; contact_name: string | null; contact_email: string | null }>('SELECT name, sap_code, address, contact_name, contact_email FROM vendors WHERE id = ?', vendorId) : undefined;
  const buyer = get<{ name: string; email: string; phone: string | null }>('SELECT name, email, phone FROM users WHERE id = ?', r.buyer_id);
  const lines = linesOf(r.id).filter((l) => l.status !== 'Removed');
  const doc = new PDFDocument({ size: 'A4', margin: 42, info: { Title: `RFQ ${r.rfq_no}`, Author: 'Knowteq Equipcare LLP — S2P platform' } });
  const chunks: Buffer[] = [];
  doc.on('data', (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((res) => doc.on('end', () => res(Buffer.concat(chunks))));
  const W = doc.page.width - 84;

  doc.rect(0, 0, doc.page.width, 70).fill(NAVY);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(16).text('Knowteq Equipcare LLP', 42, 20);
  doc.font('Helvetica').fontSize(9).text('Request for quotation · issued through the Equipcare vendor portal', 42, 42);
  doc.rect(0, 70, doc.page.width, 4).fill(AMBER);
  doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(14).text(`RFQ ${r.rfq_no}`, 42, 90);
  doc.font('Helvetica').fontSize(10).fillColor('#000').text(r.title, { width: W });
  doc.moveDown(0.6);

  const kv = (k: string, v: string | null | undefined) => {
    const y = doc.y;
    doc.font('Helvetica-Bold').fontSize(9).fillColor(GREY).text(k, 42, y, { width: 130 });
    doc.font('Helvetica').fillColor('#000').text(v || '—', 175, y, { width: W - 133 });
    doc.moveDown(0.25);
  };
  kv('To', vendor ? `${vendor.name}${vendor.sap_code ? ` (vendor ${vendor.sap_code})` : ''}${vendor.contact_name ? `, attn. ${vendor.contact_name}` : ''}` : 'All invited vendors');
  kv('Issued', fmtIST(r.published_at ?? r.created_at));
  kv('Closing date', fmtIST(r.closing_at));
  kv('Buyer', buyer ? `${buyer.name} · ${buyer.email}${buyer.phone ? ` · ${buyer.phone}` : ''}` : null);
  kv('Delivery terms', r.delivery_terms);
  kv('Payment terms', r.payment_terms);
  kv('Warranty', r.warranty);
  kv('Packing', r.packing);
  kv('Documents required', r.documents_required);
  doc.moveDown(0.5);

  doc.font('Helvetica-Bold').fontSize(11).fillColor(NAVY).text('Lines', 42);
  doc.moveDown(0.3);
  const cols = [{ h: 'Line', w: 34 }, { h: 'Material / description', w: 200 }, { h: 'Qty', w: 60 }, { h: 'Required', w: 62 }, { h: 'Quote due', w: 62 }, { h: 'Plant', w: 40 }, { h: 'GST', w: 33 }];
  const row = (vals: string[], bold = false) => {
    const y = doc.y;
    let x = 42;
    let h = 0;
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5).fillColor(bold ? GREY : '#000');
    vals.forEach((v, i) => {
      doc.text(v, x + 2, y, { width: cols[i].w - 4 });
      h = Math.max(h, doc.y - y);
      x += cols[i].w;
    });
    doc.y = y + h + 4;
    doc.moveTo(42, doc.y - 2).lineTo(42 + W, doc.y - 2).strokeColor('#dfe5ec').lineWidth(0.5).stroke();
  };
  row(cols.map((c) => c.h), true);
  const d = (s: string | null) => (s ? s.slice(0, 10) : '—');
  for (const l of lines) {
    const m = l.material_id ? get<{ code: string; hsn: string | null }>('SELECT code, hsn FROM materials WHERE id = ?', l.material_id) : undefined;
    if (doc.y > doc.page.height - 120) doc.addPage();
    row([String(l.line_no), `${m ? `${m.code} · ` : ''}${l.description}${m?.hsn ? ` (HSN ${m.hsn})` : ''}${l.specs ? `\n${l.specs}` : ''}${l.transport_req ? `\nTransport: ${l.transport_req}` : ''}${l.valuation_type ? `\nValuation: ${l.valuation_type}` : ''}\nShip to: ${l.ship_to ?? '—'}`, `${l.qty} ${l.uom}`, d(l.required_date), d(l.due_at), l.plant ?? '—', l.gst_rate != null ? `${l.gst_rate}%` : '—']);
  }
  doc.moveDown(0.6);
  doc.font('Helvetica-Bold').fontSize(11).fillColor(NAVY).text('Standard terms', 42);
  doc.font('Helvetica').fontSize(9).fillColor('#000').text(r.standard_terms ?? '—', { width: W });
  doc.moveDown(0.6);
  doc.font('Helvetica-Bold').fontSize(9).fillColor(NAVY).text('How to respond', 42);
  doc.font('Helvetica').fontSize(9).fillColor('#000').text('Sign in to the Equipcare vendor portal, open this RFQ and enter your quotation line by line (basic price, discount, GST, freight, packing, delivery days, make / brand, warranty, validity). Upload the signed quotation and datasheets there. Quotations sent by e-mail are not accepted. You may decline with a reason.', { width: W });
  doc.moveDown(1);
  doc.fontSize(7.5).fillColor(GREY).text(`Generated by the Equipcare S2P platform on ${fmtIST(new Date().toISOString())}. All amounts in INR.`, { width: W });
  doc.end();
  return done;
}
