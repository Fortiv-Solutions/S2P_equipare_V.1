const byOa = (oa: string) => get<{ id: number; contract_no: string; title: string; vendor_id: number; valid_from: string; valid_to: string }>('SELECT * FROM contracts WHERE sap_oa_no = ?', oa);

/** Minimal one-page PDF with a few lines of text (demo document copy). */
function demoPdf(lines: string[]) {
  const text = lines.map((l, i) => `BT /F1 ${i === 0 ? 14 : 10} Tf 56 ${780 - i * 20} Td (${l.replace(/[()\\]/g, '')}) Tj ET`).join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${text.length} >>\nstream\n${text}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let out = '%PDF-1.4\n';
  const offs: number[] = [];
  objs.forEach((o, i) => { offs.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offs.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

export function seed() {
  const sneha = actorFor('sneha.patil');
  const amit = actorFor('amit.kulkarni');

  // Documents on synced OAs (AC-CON-01: docs shown with the SAP OA).
  for (const [oa, label] of [['5500000101', 'Signed rate contract'], ['5500000102', 'VMI agreement'], ['5500000103', 'Discount structure letter'], ['5500000104', 'Signed rate contract']] as const) {
    const c = byOa(oa);
    if (!c) continue;
    storeGenerated(demoPdf([`${label} - demo copy`, `${c.title}`, `SAP outline agreement ${oa}`, `Validity ${c.valid_from} to ${c.valid_to}`, 'Fictional demo document generated by the platform seed.']),
      `${oa}-${label.toLowerCase().replace(/\s+/g, '-')}.pdf`, 'application/pdf', { ownerType: 'contract', ownerId: c.id, label, vendorVisible: true });
  }

  // Kranti FDS: price lists v1/v2/v3 (v3 from 2026-04-01) with 12% discount; invoice validation on (AC-CON-05).
  const fds = byOa('5500000103');
  if (fds) {
    const ids = { t1: M('TLS-7001'), t2: M('TLS-7002'), p1: M('PPE-8001') };
    const versions: [number, string, [number, number, number], string][] = [
      [1, '2025-04-01', [172000, 32000, 1540], 'FY 2025-26 catalogue'],
      [2, '2025-10-01', [178500, 33400, 1600], 'Mid-year steel price revision'],
      [3, '2026-04-01', [185000, 34500, 1650], 'FY 2026-27 catalogue'],
    ];
    for (const [v, eff, [a, b, c], note] of versions) {
      insert('price_lists', { contract_id: fds.id, version: v, effective_from: eff, items_json: J([{ material_id: ids.t1, list_price: a }, { material_id: ids.t2, list_price: b }, { material_id: ids.p1, list_price: c }]), created_by: sneha.id, created_at: now(), note });
    }
    update('contracts', fds.id, { discount_pct: 12, invoice_validation: 1, price_list_version: 3, price_revision_date: '2027-04-01', terms: 'Fixed 12% discount on the vendor price list version effective on the PO date. Invoices are validated against that version (FR-INV-18).' });
    audit(sneha, { action: 'contract.price_list_added', objectType: 'contract', objectId: fds.id, objectRef: fds.contract_no, after: { versions: [1, 2, 3], discount_pct: 12, invoice_validation: true } });
  }

  // Precision Filtration VMI terms (FLT-4002 stock 3 < min 10 raises NTF-15; AC-CON-06).
  const vmi = byOa('5500000102');
  if (vmi) {
    S.setVmiTerms(sneha, vmi.id, {
      items: [{ material_id: M('FLT-4001'), min: 30, max: 120 }, { material_id: M('FLT-4002'), min: 10, max: 40 }, { material_id: M('FLT-4003'), min: 6, max: 24 }],
      replenishment_frequency: 'Weekly', billing_cycle: 'Monthly on consumption (GRN of issues)', reconciliation: 'Joint physical count with Chakan stores on the last working day of each month; variances settled on the next consumption invoice.', plant: 'PUN1',
    }, 'VMI terms from the signed VMI agreement');
  }

  // Platform ARC for Bharat Bearings: Draft → approved → Pending SAP (FR-CON-09: not routable yet).
  try {
    const c = S.createContract(amit, {
      type: 'ARC', vendor_id: V('100103'), title: 'Annual rate contract – final drive bearings (Bharat)', category: 'ENG', plant: '*',
      valid_from: DAY(0), valid_to: DAY(364), value_cap: 600000, payment_terms: '45 days from GRN', delivery_terms: 'FOR destination',
      terms: 'Rate firm for 12 months. Delivery within 10 days of PO. Price revision only on SKF list price change above 5%.',
      items: [{ material_id: M('ENG-3002'), unit_price: 45000, qty_cap: 12 }],
    });
    S.submitContract(amit, c.id, 'Two POs in 7 months at ₹45,500–46,200; ARC at ₹45,000 agreed after negotiation.');
    const ap = get<{ id: number }>("SELECT id FROM approvals WHERE object_type = 'contract' AND object_id = ?", c.id)!;
    act(actorFor('vikram.joshi', 'APR'), ap.id, 'approve', 'Rate below last purchase price — approved.');
    act(actorFor('meera.iyer'), ap.id, 'approve', 'Budget available under engine spares.');
  } catch (e) {
    console.warn('contracts seed: Bharat ARC scenario skipped —', (e as Error).message);
  }

  // Jobs: expiry (Shakti ARC ~34 days → Expiring, NTF-13) and opportunities (HYD-1001, WLD-6001).
  S.expiryJob();
  S.opportunityJob();

  // Off-contract SAP PO: UCG-2003 bought from Coromandel (100115) without OA reference while Shakti ARC is valid (AC-CON-03).
  try {
    V('100115');
    sapPut('PO', '4500021012', {
      po_no: '4500021012', vendor_sap_code: '100115', buyer_email: 'amit.kulkarni@equipcare.test', plant: 'PUN1', po_date: DAY(-1), released: true, version: 1,
      delivery_terms: 'FOR destination', payment_terms: '45 days from GRN', freight_terms: 'Freight paid', oa_no: null, urgency: 'General stock',
      items: [{ item: 10, material_code: 'UCG-2003', description: 'Bucket tooth point, heavy duty – PC2000', qty: 30, uom: 'EA', unit_price: 7980, gst_rate: 18, freight: 0, delivery_date: DAY(10) }],
    }, 'Seed');
    syncEvent('PO');
  } catch (e) {
    console.warn('contracts seed: off-contract PO scenario skipped —', (e as Error).message);
  }

  if (DEMO_EXTRA) seedExtra();
}
