/** A small, valid one-page PDF with a few lines of text (demo documents). */
export function demoPdf(title: string, lines: string[]) {
  const esc = (s: string) => s.replace(/[\\()]/g, (c) => `\\${c}`).replace(/[^\x20-\x7e]/g, '-');
  const text = [`BT /F1 16 Tf 56 780 Td (${esc(title)}) Tj ET`, ...lines.map((l, i) => `BT /F1 11 Tf 56 ${748 - i * 18} Td (${esc(l)}) Tj ET`), 'BT /F1 9 Tf 56 60 Td (Demo document generated by the Equipcare S2P MVP seed - fictional data.) Tj ET'].join('\n');
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(text)} >>\nstream\n${text}\nendstream`,
  ];
  let out = '%PDF-1.4\n';
  const offs: number[] = [];
  objs.forEach((o, i) => { offs.push(Buffer.byteLength(out)); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offs.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out);
}

/** A plain PNG "photo" placeholder (solid colour with a darker band) — real camera photos replace these in use. */
export function demoPng(w = 240, h = 160, rgb: [number, number, number] = [150, 120, 80]) {
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w * 3 + 1)] = 0;
    for (let x = 0; x < w; x++) {
      const band = y > h * 0.4 && y < h * 0.6 ? 0.6 : 1;
      const o = y * (w * 3 + 1) + 1 + x * 3;
      raw[o] = rgb[0] * band; raw[o + 1] = rgb[1] * band; raw[o + 2] = rgb[2] * band;
    }
  }
  const chunk = (type: string, data: Buffer) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(zlib.crc32(td) >>> 0);
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

function doc(ownerType: string, ownerId: number, label: string, filename: string, title: string, lines: string[], actorId: number | null, vendorVisible = true) {
  return storeGenerated(demoPdf(title, lines), filename, 'application/pdf', { ownerType, ownerId, label, actorId, vendorVisible });
}
function unownedPhoto(name: string, actorId: number, rgb: [number, number, number]) {
  const id = storeGenerated(demoPng(240, 160, rgb), name, 'image/png', { ownerType: 'dispute', ownerId: 0, label: 'Photo', actorId });
  run('UPDATE attachments SET owner_type = NULL, owner_id = NULL WHERE id = ?', id);
  return id;
}

/** Seed precondition: the vendor acknowledged these lines (the PO module owns acknowledgements; only Pending lines are touched). */
function ensureAccepted(poId: number, at: string) {
  for (const l of all<{ id: number; qty: number; delivery_date: string; ack_status: string }>('SELECT id, qty, delivery_date, ack_status FROM po_lines WHERE po_id = ?', poId)) {
    if (l.ack_status === 'Pending') update('po_lines', l.id, { ack_status: 'Accepted', accepted_qty: l.qty, ack_at: at, commit_date: l.delivery_date, first_commit_date: l.delivery_date, ack_remarks: 'Accepted as ordered' });
  }
}

export interface SeedAsn {
  po: string; vendor: string; lines: [item: number, qty: number][]; status: string; dispatch: string; expected: string; created: string; submitted: string;
  transporter?: string; lr?: string; vehicle?: string; eway?: string; invoiceRef?: string; packing?: string;
  pickupBy?: 'Vendor' | 'Equipcare'; pickupDate?: string; pickupStatus?: string; delivered?: string; grn?: string; docs?: [label: string, file: string, lines: string[]][];
}

export function seedAsn(s: SeedAsn) {
  const poRow = get<{ id: number }>('SELECT id FROM pos WHERE po_no = ?', s.po);
  if (!poRow) return null;
  const po = getPo(poRow.id)!;
  ensureAccepted(po.id, s.created);
  const pl = all<{ id: number; item: number; qty: number; ack_status: string; accepted_qty: number | null; received_qty: number }>('SELECT id, item, qty, ack_status, accepted_qty, received_qty FROM po_lines WHERE po_id = ?', po.id);
  const lines: AsnLineStored[] = [];
  const delivered = s.status === 'Delivered';
  for (const [item, qty] of s.lines) {
    const l = pl.find((x) => x.item === item);
    if (!l) continue;
    // Never ship more than the vendor acknowledged (the PO module may have seeded a partial acceptance).
    const acc = acceptedQty(l);
    const q = Math.min(qty, delivered ? acc : Math.max(0, acc - (l.received_qty ?? 0)));
    if (q > 0) lines.push({ po_line_id: l.id, item, qty: q, packing: null });
  }
  if (!lines.length) return null;
  const d = termDefaults(po);
  const vendorUser = get<{ id: number }>('SELECT id FROM users WHERE email LIKE ?', `${s.vendor}@%`)?.id ?? null;
  const asnNo = nextNo('ASN');
  const id = insert('asns', {
    asn_no: asnNo, po_id: po.id, vendor_id: po.vendor_id, plant: po.plant, status: s.status, dispatch_date: s.dispatch, expected_date: s.expected,
    transporter: s.transporter ?? null, lr_no: s.lr ?? null, vehicle_no: s.vehicle ?? null, eway_bill: s.eway ?? null, invoice_ref: s.invoiceRef ?? null,
    packing_details: s.packing ?? null, delivery_terms: d.delivery_terms, freight_mode: d.freight_mode, transit_risk: d.transit_risk,
    pickup_by: s.pickupBy ?? d.pickup_by, pickup_date: s.pickupDate ?? null, pickup_status: s.pickupStatus ?? null, lines_json: J(lines), version: 1,
    created_by: vendorUser, created_at: s.created, submitted_at: s.submitted, delivered_at: s.delivered ?? null,
  });
  if (s.grn) insert('asn_grns', { asn_id: id, grn_no: s.grn, matched_by: 'po_plant', linked_at: s.delivered ?? s.submitted });
  for (const [label, file, text] of s.docs ?? []) doc('asn', id, label, file, `${label} — ${asnNo}`, [`PO ${s.po}`, ...text], vendorUser);
  audit(null, { action: 'asn.seeded', objectType: 'asn', objectId: id, objectRef: asnNo, after: { po_no: s.po, status: s.status } });
  refreshLineStatuses(po.id);
  return { id, asnNo, po };
}

function setStatus(id: number, status: string) {
  update('disputes', id, { status });
}
function ev(disputeId: number, userId: number | null, kind: string, body: string, visible: boolean, at: string) {
  insert('dispute_events', { dispute_id: disputeId, user_id: userId, kind, body, vendor_visible: visible ? 1 : 0, created_at: at });
}

